def lig_ortalamasi_hesapla(df, lig_kodu):
    lig_verileri = df[(df['Div'] == lig_kodu) & (df['Sezon'].isin(['2425','2526','2627']))]
    if lig_verileri.empty: return 1.3
    toplam_mac = len(lig_verileri)
    toplam_gol = lig_verileri['FTHG'].sum() + lig_verileri['FTAG'].sum()
    return (toplam_gol / toplam_mac) / 2

def altmis_gol_olasilik(ev_l, dep_l):
    lam = ev_l + dep_l
    if lam <= 0: return 0
    p_5_ve_alt = sum([poisson.pmf(i, lam) for i in range(6)])
    return max(0, 1 - p_5_ve_alt)

def dinamik_big_team_bonus(takim, seri):
    if takim not in BIG_TEAMS: return 0
    if seri.startswith("GG"): return 10
    elif seri.startswith("G"): return 6
    elif seri.startswith("B"): return 3
    else: return 0

def seri_puani_hesapla(seri):
    if not seri or seri == "Veri Yok": return 1.0
    if "GGGGG" in seri: return 1.5
    yenilmezlik = 0
    for h in seri:
        if h in ['G', 'B']: yenilmezlik += 1
        else: break
    return 1.25 if yenilmezlik >= 5 else 1.0

def get_ppg(df, takim, mode='genel'):
    temp = df[(df['HomeTeam'] == takim) | (df['AwayTeam'] == takim)] if mode=='genel' else (df[df['HomeTeam']==takim] if mode=='Home' else df[df['AwayTeam']==takim])
    if temp.empty: return 0.0
    puan = sum([3 if (r['HomeTeam']==takim and r['FTR']=='H') or (r['AwayTeam']==takim and r['FTR']=='A') else (1 if r['FTR']=='D' else 0) for _, r in temp.iterrows()])
    return puan / len(temp)

def savunma_verimliligi(df, takim, saha='H'):
    maclar = df[df['HomeTeam' if saha=='H' else 'AwayTeam'] == takim].tail(5)
    return max(0.7, maclar['FTAG' if saha=='H' else 'FTHG'].mean() / 1.3) if not maclar.empty else 1.0

def ilk_yari_savunma_verimliligi(df, takim, saha='H'):
    hedef_sutun = 'HTAG' if saha == 'H' else 'HTHG'
    filtre_sutun = 'HomeTeam' if saha == 'H' else 'AwayTeam'

    maclar = df[(df[filtre_sutun] == takim) & (df['Sezon'] == '2627')].tail(8)
    if maclar.empty or hedef_sutun not in maclar.columns:
        return 1.0

    yenen_iy_gol_ort = maclar[hedef_sutun].mean()
    if np.isnan(yenen_iy_gol_ort): return 1.0

    return max(0.7, yenen_iy_gol_ort / 0.55)

