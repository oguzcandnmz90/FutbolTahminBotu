def akilli_skor_tahmin(ev_l, dep_l, t_str, h2h_skorlar, bu_sezon_ev, bu_sezon_dep, ev, dep):
    ev_at_ort = bu_sezon_ev[bu_sezon_ev['HomeTeam']==ev]['FTHG'].tail(5).mean()
    dep_at_ort = bu_sezon_dep[bu_sezon_dep['AwayTeam']==dep]['FTAG'].tail(5).mean()

    ev_at_ort = round(ev_at_ort) if not np.isnan(ev_at_ort) else round(ev_l)
    dep_at_ort = round(dep_at_ort) if not np.isnan(dep_at_ort) else round(dep_l)

    h2h_counts = pd.Series(h2h_skorlar).value_counts().to_dict() if h2h_skorlar else {}
    skor_puanlari = {}

    for i in range(6):
        for j in range(6):
            current_skor = f"{i}-{j}"
            if "MS 1" in t_str and i <= j: continue
            if "MS 2" in t_str and j <= i: continue
            if "MS 0" in t_str and i != j: continue
            if "2.5 ÜST" in t_str and (i + j) < 3: continue
            if "2.5 ALT" in t_str and (i + j) >= 3: continue
            if "KG VAR" in t_str and (i == 0 or j == 0): continue
            if "KG YOK" in t_str and (i > 0 and j > 0): continue
            if "ÇŞ 1X" in t_str and i < j: continue
            if "ÇŞ X2" in t_str and j < i: continue
            if "HMS 1" in t_str and (i - j) < 2: continue
            if "HMS 2" in t_str and (j - i) < 2: continue

            puan = 1.0
            if current_skor in h2h_counts:
                puan += (h2h_counts[current_skor] * 2.5)

            gol_fark_ev = abs(i - ev_at_ort)
            gol_fark_dep = abs(j - dep_at_ort)
            puan += max(0, 12.0 - (3.0 * (gol_fark_ev + gol_fark_dep)))

            p_poisson = poisson.pmf(i, max(0.5, ev_l)) * poisson.pmf(j, max(0.5, dep_l))
            puan += (p_poisson * 5.0)

            if ("2.5 ÜST" in t_str or "KG VAR" in t_str) and (i + j) < 3:
                puan *= 0.1

            skor_puanlari[current_skor] = puan

    if not skor_puanlari:
        return f"{max(2, ev_at_ort)}-{max(1, dep_at_ort)}", 65.0

    best_skor = max(skor_puanlari, key=skor_puanlari.get)
    toplam_puan = sum(skor_puanlari.values())
    guven_yuzdesi = round(min(max((skor_puanlari[best_skor] / toplam_puan) * 100, 35.0), 89.0), 1)
    return best_skor, guven_yuzdesi

def akilli_iy_skor_tahmin(ms_skor, ev_l, dep_l, bu_sezon_ev, bu_sezon_dep, ev, dep, h2h_iy_skorlar):
    ms_e, ms_d = map(int, ms_skor.split('-'))
    ev_iy_gol_ort = bu_sezon_ev[bu_sezon_ev['HomeTeam']==ev]['HTHG'].tail(10).mean()
    dep_iy_gol_ort = bu_sezon_dep[bu_sezon_dep['AwayTeam']==dep]['HTAG'].tail(10).mean()

    ev_iy_gol_ort = ev_iy_gol_ort if not np.isnan(ev_iy_gol_ort) else (ev_l * 0.45)
    dep_iy_gol_ort = dep_iy_gol_ort if not np.isnan(dep_iy_gol_ort) else (dep_l * 0.45)

    ev_iy_sav = ilk_yari_savunma_verimliligi(bu_sezon_ev, ev, 'H')
    dep_iy_sav = ilk_yari_savunma_verimliligi(bu_sezon_dep, dep, 'A')

    iy_ev_l = max(0.15, ((ev_l * 0.35) + (ev_iy_gol_ort * 0.65)) * dep_iy_sav)
    iy_dep_l = max(0.15, ((dep_l * 0.35) + (dep_iy_gol_ort * 0.65)) * ev_iy_sav)

    h2h_counts = pd.Series(h2h_iy_skorlar).value_counts().to_dict() if h2h_iy_skorlar else {}
    iy_puanlari = {}

    for i in range(ms_e + 1):
        for j in range(ms_d + 1):
            current_skor = f"{i}-{j}"
            puan = 1.0
            if current_skor in h2h_counts:
                puan += (h2h_counts[current_skor] * 2.0)

            p_poisson_iy = poisson.pmf(i, iy_ev_l) * poisson.pmf(j, iy_dep_l)
            puan += (p_poisson_iy * 10.0)

            toplam_ms_gol = ms_e + ms_d
            toplam_iy_gol = i + j
            if toplam_ms_gol >= 3 and toplam_iy_gol == 0:
                puan *= 0.35
            elif toplam_ms_gol >= 4 and toplam_iy_gol >= 1:
                puan *= 1.4

            iy_puanlari[current_skor] = puan

    if not iy_puanlari:
        return f"{min(1, ms_e // 2)}-{min(1, ms_d // 2)}"
    return max(iy_puanlari, key=iy_puanlari.get)

