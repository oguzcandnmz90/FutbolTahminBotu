    ev_sav, dep_sav = savunma_verimliligi(bu_sezon_ev, ev, 'H'), savunma_verimliligi(bu_sezon_dep, dep, 'A')

    ust_oran = len(gecmis[gecmis['FTHG']+gecmis['FTAG'] >= 3]) / len(gecmis) if not gecmis.empty else 0.5
    kgv_oran = len(gecmis[(gecmis['FTHG']>0) & (gecmis['FTAG']>0)]) / len(gecmis) if not gecmis.empty else 0.5

    ev_ust_oran_sezon = len(bu_sezon_ev[(bu_sezon_ev['FTHG'] + bu_sezon_ev['FTAG']) >= 3]) / len(bu_sezon_ev)
    dep_ust_oran_sezon = len(bu_sezon_dep[(bu_sezon_dep['FTHG'] + bu_sezon_dep['FTAG']) >= 3]) / len(bu_sezon_dep)
    ev_son5_ust = len(bu_sezon_ev.tail(5)[(bu_sezon_ev['FTHG'] + bu_sezon_ev['FTAG']) >= 3]) / min(5, len(bu_sezon_ev))
    dep_son5_ust = len(bu_sezon_dep.tail(5)[(bu_sezon_dep['FTHG'] + bu_sezon_dep['FTAG']) >= 3]) / min(5, len(bu_sezon_dep))

    final_ust_skor = (ust_oran * 0.4) + (((ev_ust_oran_sezon + dep_ust_oran_sezon + ev_son5_ust + dep_son5_ust) / 4) * 0.6)

    min_mac = 5
    ev_kg_oran = 0.5 if len(bu_sezon_ev) < min_mac else len(bu_sezon_ev[(bu_sezon_ev['FTHG']>0)&(bu_sezon_ev['FTAG']>0)]) / len(bu_sezon_ev)
    dep_kg_oran = 0.5 if len(bu_sezon_dep) < min_mac else len(bu_sezon_dep[(bu_sezon_dep['FTHG']>0)&(bu_sezon_dep['FTAG']>0)]) / len(bu_sezon_dep)
    final_kg_skor = (kgv_oran * 0.4) + (((ev_kg_oran + dep_kg_oran)/2) * 0.6)

    ev_son5 = bu_sezon_ev.tail(5)
    dep_son5 = bu_sezon_dep.tail(5)
    ev_tempo = (ev_son5['FTHG'] + ev_son5['FTAG']).mean()
    dep_tempo = (dep_son5['FTHG'] + dep_son5['FTAG']).mean()
    mac_tempo = (ev_tempo + dep_tempo) / 2

    if mac_tempo < 1.9:
        final_ust_skor *= 0.92
        final_kg_skor *= 0.94
    elif mac_tempo > 3.0:
        final_ust_skor *= 1.05
        final_kg_skor *= 1.03

    if abs_diff < 15:
        if final_ust_skor >= 0.65: t_str = "2.5 ÜST"
        elif final_kg_skor >= 0.65: t_str = "KG VAR"
        elif abs_diff < 5: t_str = "MS 0"
        else: t_str = "ÇŞ 1X" if diff > 0 else "ÇŞ X2"
    elif abs_diff <= 35:
        if diff > 0: t_str = "MS 1" if ev_sav < 0.80 else "ÇŞ 1X"
        else: t_str = "MS 2" if dep_sav < 0.80 else "ÇŞ X2"
    elif abs_diff <= 85:
        t_str = "MS 1" if diff > 0 else "MS 2"
    else:
        t_str = "HMS 1" if diff > 0 else "HMS 2"

    lig_ort = lig_ortalamasi_hesapla(db, lig_kodu)
    ev_ev_mac = bu_sezon_ev[bu_sezon_ev['HomeTeam']==ev]
    dep_dep_mac = bu_sezon_dep[bu_sezon_dep['AwayTeam']==dep]

    ev_atak = ev_ev_mac['FTHG'].mean() if not ev_ev_mac.empty else lig_ort
    dep_atak = dep_dep_mac['FTAG'].mean() if not dep_dep_mac.empty else lig_ort
    ev_atak = lig_ort if np.isnan(ev_atak) else ev_atak
    dep_atak = lig_ort if np.isnan(dep_atak) else dep_atak

    ev_l = max(0.5, (ev_atak * 0.8 + lig_ort * 0.2) * (1.6 * dep_sav))
    dep_l = max(0.5, (dep_atak * 0.8 + lig_ort * 0.2) * (1.6 * ev_sav))

    gol6_prob = altmis_gol_olasilik(ev_l, dep_l)
    if gol6_prob >= 0.18:
        gol6_havuzu.append((gol6_prob, f"💣 {ev}-{dep} | 6+ GOL (%{round(gol6_prob*100,1)})"))

    lam_toplam = ev_l + dep_l
    p_alt_25 = sum([poisson.pmf(i, lam_toplam) for i in range(4)])
    ust25_prob = max(0, 1 - p_alt_25)

    if ust25_prob >= 0.52 or final_ust_skor >= 0.60:
        ust25_havuzu.append((ust25_prob, f"🔥 {ev}-{dep} | 2.5 ÜST (%{round(ust25_prob*100,1)})"))

    skor_l = [f"{int(m['FTHG'])}-{int(m['FTAG'])}" if m['HomeTeam']==ev else f"{int(m['FTAG'])}-{int(m['FTHG'])}" for _, m in gecmis.iterrows()]
    iy_skor_l = [f"{int(m['HTHG'])}-{int(m['HTAG'])}" if m['HomeTeam']==ev else f"{int(m['HTAG'])}-{int(m['HTHG'])}" for _, m in gecmis.iterrows() if 'HTHG' in m and not pd.isna(m['HTHG'])]

    iyms_l = []
    for _, m in gecmis.iterrows():
        if 'HTR' in m and not pd.isna(m['HTR']):
            iy, ms = kod_map.get(m['HTR'],'X'), kod_map.get(m['FTR'],'X')
            if m['HomeTeam'] != ev: iy, ms = ters_map.get(iy,'X'), ters_map.get(ms,'X')
            iyms_l.append(f"{iy}/{ms}")

    iyms_ozet = " | ".join([f"{k}({v}x)" for k,v in pd.Series(iyms_l).value_counts().head(3).items()]) if iyms_l else "Veri Yok"
    if iyms_l: iyms_havuzu.append((pd.Series(iyms_l).value_counts().iloc[0], f"🕒 {ev}-{dep} | {pd.Series(iyms_l).value_counts().index[0]}"))

    h_skor, h_prob = akilli_skor_tahmin(ev_l, dep_l, t_str, skor_l, bu_sezon_ev, bu_sezon_dep, ev, dep)
    iy_skor = akilli_iy_skor_tahmin(h_skor, ev_l, dep_l, bu_sezon_ev, bu_sezon_dep, ev, dep, iy_skor_l)
    iy2_skor = akilli_iy2_skor_tahmin(h_skor, iy_skor)

    kasa_havuzu.append((abs_diff, f"💎 {ev}-{dep} | {t_str}"))

    # Log listesine ekleme
    bugun_log_listesi.append({
        "tarih": bugun,
        "ay": bugun_ay_str,
        "lig": lig_kodu,
        "ev": ev,
        "dep": dep,
        "tahmin": t_str,
        "skor_tahmini": h_skor,
        "sonuc_kontrol_edildi": False,
        "gercek_skor": None,
        "tuttu": None
    })

    rapor = (f"⏰ {ham_saat} | {ev} - {dep}\n🎯 TAHMİN: {t_str}\n"
             f"🎲 SKOR TAHMİNİ: {h_skor} (%{h_prob})\n"
             f"⏱️ İLK YARI SKORU: {iy_skor}\n"
             f"⏱️ İKİNCİ YARI SKORU: {iy2_skor}\n"
             f"📍 EN ÇOK ÇIKAN 3 MS SKOR: {', '.join([f'{s}({v}x)' for s,v in pd.Series(skor_l).value_counts().head(3).items()]) if skor_l else 'Veri Yok'}\n"
             f"🕒 EN ÇOK ÇIKAN 3 İY/MS: {iyms_ozet}\n"
             f"🧤 KG VAR: {len(gecmis[(gecmis['FTHG']>0) & (gecmis['FTAG']>0)])}x | KG YOK: {len(gecmis[~((gecmis['FTHG']>0) & (gecmis['FTAG']>0))])}x\n"
             f"📊 2.5 ÜST: {len(gecmis[gecmis['FTHG']+gecmis['FTAG'] >= 3])}x | 2.5 ALT: {len(gecmis[gecmis['FTHG']+gecmis['FTAG'] < 3])}x\n"
             f"⚽ GOL ORT: E({bu_sezon_ev[bu_sezon_ev['HomeTeam']==ev]['FTHG'].mean():.1f}) D({bu_sezon_dep[bu_sezon_dep['AwayTeam']==dep]['FTAG'].mean():.1f})\n"
             f"🚩 KORNER ORT: E({(bu_sezon_ev['HC'].min() if 'HC' in bu_sezon_ev else 0):.1f} saha) D({(bu_sezon_dep['AC'].mean() if 'AC' in bu_sezon_dep else 0):.1f})\n"
             f"📈 FORM: E({ev_seri}) D({dep_seri})\n───────────────")
    analizler_listesi.append(rapor)

